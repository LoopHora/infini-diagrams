export class ShapeCompatibilityService {
  static getAllShapes(): ShapeDefinition[] {
    return SHAPE_REGISTRY;
  }

  static getShapeById(id: string): ShapeDefinition | undefined {
    const needle = id.toLowerCase();
    return (
      SHAPE_REGISTRY.find(s => s.id === needle) ||
      (SHAPE_ALIASES[needle] ? SHAPE_REGISTRY.find(s => s.id === SHAPE_ALIASES[needle]) : undefined)
    );
  }

  static getShapesByCategory(category: ShapeCategory): ShapeDefinition[] {
    return SHAPE_REGISTRY.filter(s => s.category === category);
  }

  static isValidShape(id: string): boolean {
    return this.getShapeById(id) !== undefined;
  }

  static getCanonicalCount(): number {
    return SHAPE_REGISTRY.length;
  }
}

